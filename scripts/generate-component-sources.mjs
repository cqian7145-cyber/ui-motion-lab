import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const ids=["motion-button","magnetic-button","reveal-text","morph-card","stagger-list","animated-tabs","scroll-reveal","bottom-sheet","animated-toast","page-transition"];
const data={};
for(const id of ids) {
  const filename=path.join(root,"src","components","motion",`${id}.tsx`);
  data[id]=fs.readFileSync(filename,"utf8");
}
const dest=path.join(root,"src","generated","component-sources.ts");
fs.mkdirSync(path.dirname(dest),{recursive:true});
fs.writeFileSync(dest,`// GENERATED by npm run generate:sources. Do not edit manually.\nexport const componentSources: Record<string,string> = ${JSON.stringify(data,null,2)};\n`);
console.log(`Generated ${ids.length} source entries`);
